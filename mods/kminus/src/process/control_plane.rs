/// Spawn the control-plane and wait until it reports itself ready in its
/// heartbeat file — which it writes only once etcd, the API server and
/// kube-controller-manager have all answered their own health probes.
/// Exits the process on failure.
// Launcher-style: every parameter is an independent value the caller
// already has, so bundling them into a struct moves the list rather
// than shortening it.
#[allow(clippy::too_many_arguments)]
pub fn start(
    workdir: &Path,
    configdir: &Path,
    logdir: &Path,
    pids: &Path,
    sys_cfg: &KmSysConfig,
    port_api: &str,
    port_kcm: &str,
    run: &Run,
    components: &Components,
) {
    info!("Starting {}...", BIN);
    let cp_bin = resolve_binary(BIN);
    let log_max_size = sys_cfg.log.max_size_mb.to_string();
    let log_max_files = sys_cfg.log.max_files.to_string();
    let port_etcd = sys_cfg.ports.etcd.to_string();
    let port_etcd_peer = sys_cfg.ports.etcd_peer.to_string();
    let heartbeat = heartbeat_file(workdir, BIN);
    let heartbeat_secs = sys_cfg.heartbeat.interval().as_secs().to_string();
    let max_missed = sys_cfg.heartbeat.max_missed().to_string();
    let startup_secs = sys_cfg.heartbeat.startup_timeout().as_secs().to_string();
    heartbeat::clear(&heartbeat);
    let mut command = Command::new(&cp_bin);
    command.args([
        "-workdir",
        workdir.to_str().unwrap(),
        "-configdir",
        configdir.to_str().unwrap(),
        "-logdir",
        logdir.to_str().unwrap(),
        "-logmaxsizemb",
        &log_max_size,
        "-logmaxfiles",
        &log_max_files,
        "-port",
        port_api,
        "-kcm-port",
        port_kcm,
        "-etcd-port",
        &port_etcd,
        "-etcd-peer-port",
        &port_etcd_peer,
        "-heartbeat-file",
        heartbeat.to_str().unwrap(),
        "-heartbeat-secs",
        &heartbeat_secs,
        "-max-missed-heartbeats",
        &max_missed,
        // Its own budget, not the steady-state one: the control-plane
        // applies it to etcd, the API server and kube-controller-manager
        // all answering their health probes.
        "-startup-secs",
        &startup_secs,
    ]);
    let cp = spawn_component(command, logdir, BIN, KM_KILL_TOKEN_VAR, &run.scope(BIN))
        .unwrap_or_else(|e| panic!("Failed to start {}: {}", BIN, e));

    let pid = cp.pid();
    write_pid(pids, BIN, pid);
    // Registered before the readiness gate, so the watcher already covers it.
    components.register(BIN, cp);

    if !heartbeat::wait_until_ready(BIN, &heartbeat, sys_cfg.heartbeat.startup_timeout()) {
        // Claimed before the children are killed below, so the process
        // watcher does not report those kills as a liveness failure.
        if !crate::exit::claim() {
            std::process::exit(1);
        }
        crate::exit::report(&crate::exit::ExitReason::Readiness {
            component: BIN,
            detail: format!(
                "did not report ready within {}s ({})",
                sys_cfg.heartbeat.startup_timeout().as_secs(),
                heartbeat.display()
            ),
        });
        components.teardown(pids);
        std::process::exit(1);
    }
    info!(pid, "{} ready", BIN);
}

/// The control-plane's pids directory under
/// `<workdir>/data/control-plane/pids/`.
pub fn pids_dir_in(workdir: &Path) -> PathBuf {
    pids_dir(workdir, BIN)
}

/// Read the control-plane's subprocess PIDs (etcd, kube-apiserver,
/// kube-controller-manager) from `<workdir>/data/control-plane/pids/`.
/// Returns `[(name, pid_string)]` sorted by name. The control-plane's
/// own PID file is excluded (already known to the caller).
pub fn read_children(workdir: &Path) -> Vec<(String, String)> {
    let cp_pids_dir = pids_dir_in(workdir);
    let mut children: Vec<(String, String)> = Vec::new();
    if let Ok(entries) = fs::read_dir(&cp_pids_dir) {
        for entry in entries.filter_map(|e| e.ok()) {
            let fname = entry.file_name();
            let fname = fname.to_string_lossy();
            if let Some(dot) = fname.find('.') {
                let pid = &fname[..dot];
                let name = &fname[dot + 1..];
                if name != BIN {
                    children.push((name.to_string(), pid.to_string()));
                }
            }
        }
    }
    children.sort_by(|a, b| a.0.cmp(&b.0));
    children
}

/// On restart, the previous virtual-kubelet's node and lease still
/// exist in etcd. The new VK fails to re-register if they are present.
/// Best-effort cleanup of all nodes and node leases via kmc.
pub fn cleanup_stale_node_resources(kubeconfig: &Path) {
    let kmc = resolve_binary(BIN_KMC);
    if !kmc.exists() {
        return;
    }
    info!("Cleaning up stale K8s node resources...");
    let mut delete_nodes = Command::new(&kmc);
    delete_nodes
        .args([
            "--kubeconfig",
            kubeconfig.to_str().unwrap(),
            "delete",
            "nodes",
            "--all",
            "--ignore-not-found",
        ])
        .stdout(Stdio::null())
        .stderr(Stdio::null());
    apply_detached_flags(&mut delete_nodes);
    let _ = delete_nodes.status();

    let mut delete_leases = Command::new(&kmc);
    delete_leases
        .args([
            "--kubeconfig",
            kubeconfig.to_str().unwrap(),
            "delete",
            "leases",
            "--all",
            "-n",
            "kube-node-lease",
            "--ignore-not-found",
        ])
        .stdout(Stdio::null())
        .stderr(Stdio::null());
    apply_detached_flags(&mut delete_leases);
    let _ = delete_leases.status();
}

/// Delete every workload a previous run left in the cluster: pod owners
/// first (cronjobs, deployments, replicasets, jobs), then the pods
/// themselves. Secrets, configmaps and every other non-workload resource
/// are left untouched.
///
/// Runs after the control-plane is up and before the virtual-kubelet
/// starts, so stale pods are never dispatched only to be killed. That
/// same absence is why the pod pass must force-delete: a normal delete
/// waits for a kubelet — not there — to confirm a termination that
/// already happened, since the processes those pods described died with
/// the run that owned them.
///
/// Owners go first because the controller-manager is already running: an
/// owner marked for deletion stops reproducing, so by the time the pod
/// pass lists its victims nothing recreates them.
pub fn purge_workloads(kubeconfig: &Path) {
    let kmc = resolve_binary(BIN_KMC);
    if !kmc.exists() {
        warn!(kmc = %kmc.display(), "kmc not found; cannot purge workloads");
        return;
    }
    info!("Purging previous-run workloads...");
    purge(
        &kmc,
        kubeconfig,
        &[
            "delete",
            "cronjobs,deployments,replicasets,jobs",
            "--all",
            "--all-namespaces",
            "--ignore-not-found",
            "--wait=false",
        ],
        "workload owners",
    );
    purge(
        &kmc,
        kubeconfig,
        &[
            "delete",
            "pods",
            "--all",
            "--all-namespaces",
            "--force",
            "--grace-period=0",
            "--ignore-not-found",
            "--wait=false",
        ],
        "pods",
    );
}

/// One `kmc delete` pass, reporting how many objects fell.
fn purge(kmc: &Path, kubeconfig: &Path, args: &[&str], what: &str) {
    let mut command = Command::new(kmc);
    command
        .arg("--kubeconfig")
        .arg(kubeconfig)
        .args(args)
        .stdout(Stdio::piped())
        .stderr(Stdio::null());
    apply_detached_flags(&mut command);
    match command.output() {
        Ok(out) => {
            // kubectl prints one line per deleted object.
            let deleted = String::from_utf8_lossy(&out.stdout)
                .lines()
                .filter(|l| !l.is_empty())
                .count();
            if out.status.success() {
                info!(deleted, what, "Purged");
            } else {
                warn!(deleted, what, status = %out.status, "Purge did not complete cleanly");
            }
        }
        Err(e) => warn!(what, error = %e, "Cannot run kmc to purge"),
    }
}

/// Query K8s for pods scheduled on `node_name`. Returns the raw
/// `kmc get pods --no-headers` lines, or empty on any failure.
pub fn list_pods_on_node(kubeconfig: &Path, node_name: &str) -> Vec<String> {
    let kmc = resolve_binary(BIN_KMC);
    if !kmc.exists() {
        return Vec::new();
    }
    let mut command = Command::new(&kmc);
    command
        .args([
            "--kubeconfig",
            kubeconfig.to_str().unwrap(),
            "get",
            "pods",
            "--all-namespaces",
            "--field-selector",
            &format!("spec.nodeName={}", node_name),
            "--no-headers",
        ])
        .stdout(Stdio::piped())
        .stderr(Stdio::null());
    apply_detached_flags(&mut command);
    let output = command.output();
    let Ok(out) = output else { return Vec::new() };
    String::from_utf8_lossy(&out.stdout)
        .lines()
        .filter(|l| !l.is_empty())
        .map(|l| l.to_string())
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::env;
    use std::path::PathBuf;

    fn tempdir() -> PathBuf {
        use std::sync::atomic::{AtomicU64, Ordering};
        static COUNTER: AtomicU64 = AtomicU64::new(0);
        let n = COUNTER.fetch_add(1, Ordering::Relaxed);
        let dir = env::temp_dir().join(format!("km-cp-{}-{}", std::process::id(), n));
        fs::create_dir_all(&dir).unwrap();
        dir
    }

    // -- etcd storage report -----------------------------------------------

    #[test]
    fn human_bytes_scales_units() {
        assert_eq!(human_bytes(512), "512B");
        assert_eq!(human_bytes(2048), "2.0KiB");
        assert_eq!(human_bytes(5 * 1024 * 1024), "5.0MiB");
        assert_eq!(human_bytes(4096 * 1024 * 1024), "4.0GiB");
    }

    #[test]
    fn read_etcd_storage_none_when_missing() {
        let dir = tempdir();
        assert!(read_etcd_storage(&dir).is_none());
        fs::remove_dir_all(&dir).ok();
    }

    #[test]
    fn read_etcd_storage_none_when_unparseable() {
        let dir = tempdir();
        let path = etcd_storage_file(&dir);
        fs::create_dir_all(path.parent().unwrap()).unwrap();
        fs::write(&path, "not a report").unwrap();
        assert!(read_etcd_storage(&dir).is_none());
        fs::remove_dir_all(&dir).ok();
    }

    // The control-plane writes JSON; km parses it with its YAML reader.
    #[test]
    fn read_etcd_storage_reads_the_control_plane_json() {
        let dir = tempdir();
        let path = etcd_storage_file(&dir);
        fs::create_dir_all(path.parent().unwrap()).unwrap();
        fs::write(
            &path,
            r#"{"ts":1787407408,"dbSize":314572800,"dbSizeInUse":41943040,
                "quotaBytes":4294967296,"defragMins":60,"fsync":true,
                "dataDir":"/tmp/wd/data/control-plane"}"#,
        )
        .unwrap();

        let got = read_etcd_storage(&dir).expect("report should parse");
        assert_eq!(got.db_size, 314_572_800);
        assert_eq!(got.db_size_in_use, 41_943_040);
        assert_eq!(got.quota_bytes, 4_294_967_296);
        assert_eq!(got.defrag_mins, 60);
        assert!(got.fsync);
        assert_eq!(got.data_dir, "/tmp/wd/data/control-plane");
        fs::remove_dir_all(&dir).ok();
    }

    // A report from a newer control-plane carrying unknown fields must still
    // read, and absent fields must default rather than fail the whole parse.
    #[test]
    fn read_etcd_storage_tolerates_unknown_and_missing_fields() {
        let dir = tempdir();
        let path = etcd_storage_file(&dir);
        fs::create_dir_all(path.parent().unwrap()).unwrap();
        fs::write(&path, r#"{"dbSize":100,"somethingNew":"ignored"}"#).unwrap();

        let got = read_etcd_storage(&dir).expect("report should still parse");
        assert_eq!(got.db_size, 100);
        assert_eq!(got.db_size_in_use, 0);
        assert!(!got.fsync);
        fs::remove_dir_all(&dir).ok();
    }

    #[test]
    fn etcd_storage_file_sits_in_the_control_plane_data_dir() {
        let path = etcd_storage_file(Path::new("/wd"));
        assert!(path.ends_with(ETCD_STORAGE_FILE));
        assert_eq!(
            path,
            pids_dir_in(Path::new("/wd"))
                .parent()
                .unwrap()
                .join(ETCD_STORAGE_FILE)
        );
    }

    #[test]
    fn read_children_empty_when_dir_missing() {
        let dir = tempdir();
        assert!(read_children(&dir).is_empty());
        fs::remove_dir_all(&dir).ok();
    }

    #[test]
    fn read_children_lists_pid_files_excluding_self() {
        let dir = tempdir();
        let pids_dir = pids_dir_in(&dir);
        fs::create_dir_all(&pids_dir).unwrap();
        fs::write(pids_dir.join("11.etcd"), "11").unwrap();
        fs::write(pids_dir.join("22.kube-apiserver"), "22").unwrap();
        fs::write(pids_dir.join("33.control-plane"), "33").unwrap();
        let children = read_children(&dir);
        let names: Vec<String> = children.iter().map(|(n, _)| n.clone()).collect();
        assert_eq!(names, vec!["etcd", "kube-apiserver"]);
        assert_eq!(children[0].1, "11");
        assert_eq!(children[1].1, "22");
        fs::remove_dir_all(&dir).ok();
    }

    #[test]
    fn read_children_skips_files_without_dot() {
        let dir = tempdir();
        let pids_dir = pids_dir_in(&dir);
        fs::create_dir_all(&pids_dir).unwrap();
        fs::write(pids_dir.join("nodot"), "x").unwrap();
        fs::write(pids_dir.join("44.foo"), "44").unwrap();
        let children = read_children(&dir);
        assert_eq!(children.len(), 1);
        assert_eq!(children[0].0, "foo");
        fs::remove_dir_all(&dir).ok();
    }

    #[test]
    fn cleanup_stale_node_resources_no_kmc_no_op() {
        let dir = tempdir();
        cleanup_stale_node_resources(&dir.join("kubeconfig"));
        fs::remove_dir_all(&dir).ok();
    }

    #[test]
    fn purge_workloads_no_kmc_no_op() {
        let dir = tempdir();
        purge_workloads(&dir.join("kubeconfig"));
        fs::remove_dir_all(&dir).ok();
    }

    #[test]
    fn list_pods_on_node_returns_a_vec() {
        let dir = tempdir();
        // Returns whatever the resolved kmc reports; we only check it
        // does not panic and yields a Vec.
        let _pods = list_pods_on_node(&dir.join("kubeconfig"), "tdknode");
        fs::remove_dir_all(&dir).ok();
    }
}
