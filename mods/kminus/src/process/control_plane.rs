/// Binary name for the control-plane subprocess.
pub const BIN: &str = "control-plane";

/// Name of the single node the virtual-kubelet registers.
pub const NODE_NAME: &str = "tdknode";

/// Binary name for the kmc helper used by status gathering and
/// node cleanup. Kept here because both consumers live in this module.
pub const BIN_KMC: &str = "kmc";

/// Name of the kube-controller-manager subprocess (managed by the
/// control-plane binary, but referenced by name in port checks).
pub const KCM: &str = "kube-controller-manager";

/// Name of the etcd subprocess. Started by the control-plane's envtest, and
/// named here because km allocates its ports and reports them in `km status`.
pub const ETCD: &str = "etcd";

/// Name of the kube-apiserver subprocess, for the same reason.
pub const KUBE_APISERVER: &str = "kube-apiserver";

/// Filename of the etcd backend report the control-plane publishes into
/// `<workdir>/data/control-plane/`. km cannot ask etcd itself: it speaks no
/// HTTP, and with `portstart: 0` it does not keep the random port it handed
/// out — so the process that does know publishes what `km status` shows.
pub const ETCD_STORAGE_FILE: &str = "etcd-storage.json";

/// What the control-plane last observed about etcd's backend file.
///
/// `db_size` is the file on disk and `db_size_in_use` the part of it holding
/// live data; the difference is free pages, which etcd reuses but never
/// returns to the filesystem, and which still count against `quota_bytes`.
/// Every field defaults, so a report written by a newer control-plane with
/// extra fields still reads here.
#[derive(Debug, Default, Deserialize)]
#[serde(default)]
pub struct EtcdStorage {
    pub ts: i64,
    #[serde(rename = "dbSize")]
    pub db_size: u64,
    #[serde(rename = "dbSizeInUse")]
    pub db_size_in_use: u64,
    #[serde(rename = "quotaBytes")]
    pub quota_bytes: u64,
    #[serde(rename = "defragMins")]
    pub defrag_mins: u32,
    pub fsync: bool,
    #[serde(rename = "dataDir")]
    pub data_dir: String,
}

/// Path of the etcd storage report for an instance.
pub fn etcd_storage_file(workdir: &Path) -> PathBuf {
    workdir.join(DATA_DIR).join(BIN).join(ETCD_STORAGE_FILE)
}

/// Read the etcd storage report. `None` when it is missing, unreadable or
/// unparseable — the control-plane has simply never published one, which is
/// the normal state for an instance that has not started yet.
pub fn read_etcd_storage(workdir: &Path) -> Option<EtcdStorage> {
    let data = fs::read_to_string(etcd_storage_file(workdir)).ok()?;
    // JSON is a subset of YAML, so km's existing YAML parser reads it —
    // the same trick the heartbeat reader uses, and the reason km needs no
    // JSON dependency of its own.
    serde_yaml::from_str(&data).ok()
}

/// Render a byte count the way `km status` shows it.
pub fn human_bytes(n: u64) -> String {
    const UNIT: u64 = 1024;
    if n < UNIT {
        return format!("{n}B");
    }
    let mut div = UNIT;
    let mut exp = 0usize;
    let mut v = n / UNIT;
    while v >= UNIT {
        div *= UNIT;
        v /= UNIT;
        exp += 1;
    }
    format!(
        "{:.1}{}iB",
        n as f64 / div as f64,
        ["K", "M", "G", "T", "P"][exp]
    )
}

